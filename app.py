@st.cache_resource
def load_lung_model():
    """
    Loads the compiled Keras model securely
    and caches it in memory.
    """

    try:
        return tf.keras.models.load_model(
            MODEL_PATH
        )

    except Exception as e:
        st.error(
            "CRITICAL ERROR: Unable to load "
            "the trained Deep CNN model."
        )

        st.exception(e)
        st.stop()


