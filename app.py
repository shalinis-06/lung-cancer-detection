# ========================================================
# INFERENCE PIPELINE
# ========================================================

if uploaded_file is not None:

    # Open image and force RGB conversion
    original_image = (
        Image.open(uploaded_file)
        .convert("RGB")
    )

    st.write("")

    col_img, col_analysis = st.columns(
        2,
        gap="large"
    )

    # ====================================================
    # COLUMN 1: DISPLAY UPLOADED IMAGE
    # ====================================================

    with col_img:

        with st.container(border=True):

            st.subheader(
                "Original Scan"
            )

            st.caption(
                "Patient radiological data "
                "pending analysis"
            )

            st.image(
                original_image,
                use_container_width=True
            )

    # ====================================================
    # COLUMN 2: ANALYSIS EXECUTION
    # ====================================================

    with col_analysis:

        with st.container(border=True):

            st.subheader(
                "Neural Network Analysis"
            )

            st.caption(
                "Execute feed-forward propagation "
                "through the CNN"
            )

            analyze_button = st.button(
                "Initialize Scan Analysis",
                use_container_width=True
            )

            if analyze_button:

                with st.spinner(
                    "Processing spatial features "
                    "and detecting anomalies..."
                ):

                    # 1. Resize image
                    resized_img = (
                        original_image.resize(
                            IMG_SIZE
                        )
                    )

                    # 2. Convert to NumPy array
                    img_array = np.array(
                        resized_img
                    )

                    # 3. Add batch dimension
                    # Shape: (1, 256, 256, 3)
                    img_array = np.expand_dims(
                        img_array,
                        axis=0
                    )

                    # Normalization is embedded
                    # inside the Keras model

                    # 4. Predict
                    probability = float(
                        model.predict(
                            img_array,
                            verbose=0
                        )[0][0]
                    )

                    # 5. Evaluate threshold
                    if probability >= 0.5:

                        prediction = (
                            "MALIGNANT "
                            "(LUNG CANCER)"
                        )

                        confidence = probability

                        st.error(
                            f"ALERT: {prediction}"
                        )

                        st.write(
                            "The deep learning model "
                            "detected visual biomarkers "
                            "heavily associated with "
                            "malignant lung tissue."
                        )

                    else:

                        prediction = (
                            "BENIGN (NORMAL)"
                        )

                        confidence = (
                            1.0 - probability
                        )

                        st.success(
                            f"SUCCESS: {prediction}"
                        )

                        st.write(
                            "The deep learning model "
                            "found no significant visual "
                            "biomarkers associated with "
                            "lung cancer."
                        )

                    # Display confidence
                    st.metric(
                        "Neural Network Confidence Score",
                        f"{confidence * 100:.2f}%"
                    )

                    st.progress(
                        confidence
                    )

